// Emits one js/world/<type>s.js shard per content type. Shards are plain
// classic scripts that mutate a pre-existing window.W.* namespace.

const BANNER = '// GENERATED by build.js — do not edit by hand.';

function emitManifest(schemaVersion) {
  return [
    BANNER,
    'window.W = window.W || {};',
    "W.regions = {}; W.tilemaps = {}; W.settlements = {}; W.buildings = {};",
    "W.npcs = {}; W.dialogues = {}; W.quests = {}; W.items = {};",
    "W.factions = {}; W.classes = {}; W.arcs = {}; W.encounters = {};",
    'W.overworld = null;',
    `W.schemaVersion = ${schemaVersion};`,
    '',
  ].join('\n');
}

function emitShard(type, records) {
  const ns = namespaceFor(type);
  const out = [BANNER, ''];
  // Stable key order for clean diffs.
  const keys = Object.keys(records).sort();
  if (ns === null) {
    // singleton (overworld).
    if (keys.length > 1) throw new Error(`multiple ${type} records; only one allowed`);
    if (keys.length === 0) { out.push(`W.overworld = null;`, ''); return out.join('\n'); }
    out.push(`W.overworld = ${jsLiteral(records[keys[0]], 0)};`, '');
    return out.join('\n');
  }
  for (const id of keys) {
    out.push(`W.${ns}[${JSON.stringify(id)}] = ${jsLiteral(records[id], 0)};`);
  }
  out.push('');
  return out.join('\n');
}

function namespaceFor(type) {
  // Map type -> W.<namespace>.
  if (type === 'overworld') return null;
  return type + 's'; // region -> regions, npc -> npcs, etc.
}

function jsLiteral(v, depth) {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'number' || typeof v === 'boolean') return String(v);
  if (typeof v === 'string') return JSON.stringify(v);
  if (Array.isArray(v)) {
    if (v.length === 0) return '[]';
    const inner = v.map((x) => jsLiteral(x, depth + 1)).join(', ');
    return `[${inner}]`;
  }
  if (typeof v === 'object') {
    const keys = Object.keys(v).sort();
    if (keys.length === 0) return '{}';
    const pad = '  '.repeat(depth + 1);
    const parts = keys.map((k) => `${pad}${JSON.stringify(k)}: ${jsLiteral(v[k], depth + 1)}`);
    return `{\n${parts.join(',\n')}\n${'  '.repeat(depth)}}`;
  }
  throw new Error('unexpected value type: ' + typeof v);
}

module.exports = { emitManifest, emitShard, BANNER };
